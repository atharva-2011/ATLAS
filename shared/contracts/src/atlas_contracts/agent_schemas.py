"""Structured output schemas for specialized multi-agent research intelligence.

Defines typed Pydantic models for:
- LLM prompt & response messages, token usage, and cost tracking
- Planner agent outputs (decomposed subtasks, dependencies, criteria)
- Researcher agent outputs (findings, citations, evidence extraction)
- Evidence verifier outputs (claim verification status and rationale)
- Critic agent outputs (gaps, contradictions, bias, revision needs)
- Synthesizer agent outputs (final report structure, citations, limitations)
"""

from datetime import UTC, datetime
from enum import StrEnum
from typing import Any
from uuid import UUID, uuid4

from pydantic import BaseModel, Field


def get_utc_now() -> datetime:
    return datetime.now(UTC)


# ============================================================================
# LLM Usage & Execution Tracking
# ============================================================================


class LLMMessageRole(StrEnum):
    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"
    TOOL = "tool"


class LLMMessage(BaseModel):
    """Normalized chat message."""

    role: LLMMessageRole
    content: str
    name: str | None = None


class LLMUsage(BaseModel):
    """Token accounting and estimated cost."""

    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    estimated_cost_usd: float = 0.0


class LLMResponse(BaseModel):
    """Raw or structured completion response from an LLM provider."""

    content: str
    parsed: Any | None = None
    model: str
    provider: str
    usage: LLMUsage = Field(default_factory=LLMUsage)
    latency_ms: float = 0.0
    finish_reason: str = "stop"


# ============================================================================
# 1. Planner Output Schemas
# ============================================================================


class PlannedSubtask(BaseModel):
    """Single decomposed subtask generated by the Planner."""

    task_id: str = Field(default_factory=lambda: f"task_{uuid4().hex[:6]}")
    objective: str = Field(..., min_length=5, description="Clear, unambiguous sub-question")
    agent_type: str = Field(
        default="document_researcher",
        description="Target specialist: document_researcher, web_researcher, domain_researcher",
    )
    dependencies: list[str] = Field(
        default_factory=list, description="IDs of preceding tasks required"
    )
    search_queries: list[str] = Field(
        default_factory=list, description="Initial suggested search phrases"
    )
    success_criteria: str = Field(..., description="Verifiable completion condition")


class PlannerOutput(BaseModel):
    """Complete research decomposition produced by Planner agent."""

    query: str
    plan_summary: str
    scope_dimensions: list[str] = Field(default_factory=list)
    subtasks: list[PlannedSubtask] = Field(..., min_length=1)
    estimated_depth: str = "medium"


# ============================================================================
# 2. Researcher Output Schemas
# ============================================================================


class ExtractedEvidenceItem(BaseModel):
    """Atomic factual evidence item extracted from internal documents or web."""

    evidence_id: str = Field(default_factory=lambda: f"ev_{uuid4().hex[:6]}")
    claim: str = Field(..., min_length=3, description="Material assertion or finding")
    source_passage: str = Field(..., min_length=5, description="Exact supporting text excerpt")
    source_type: str = Field(default="internal_document", description="internal_document or web")
    document_id: UUID | None = None
    url: str | None = None
    locator: dict[str, Any] = Field(default_factory=dict, description="Page, section, or line")
    confidence: float = Field(default=0.9, ge=0.0, le=1.0)


class ResearcherOutput(BaseModel):
    """Structured findings and evidence produced by Document or Web Researcher."""

    task_id: str
    summary_findings: str
    evidence_items: list[ExtractedEvidenceItem] = Field(default_factory=list)
    unresolved_questions: list[str] = Field(default_factory=list)
    sources_consulted: int = 0


# ============================================================================
# 3. Verifier Output Schemas
# ============================================================================


class ClaimVerificationVerdict(StrEnum):
    SUPPORTED = "supported"
    PARTIALLY_SUPPORTED = "partially_supported"
    CONTRADICTED = "contradicted"
    UNSUPPORTED = "unsupported"


class VerifiedClaim(BaseModel):
    """Verification result for an individual claim against its referenced passage."""

    claim: str
    evidence_id: str
    verdict: ClaimVerificationVerdict
    rationale: str
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    contradiction_details: str | None = None


class VerifierOutput(BaseModel):
    """Batch verification output produced by Evidence Verifier."""

    total_claims: int
    verified_claims: list[VerifiedClaim] = Field(default_factory=list)
    overall_support_ratio: float = Field(default=1.0, ge=0.0, le=1.0)
    has_contradictions: bool = False


# ============================================================================
# 4. Critic Output Schemas
# ============================================================================


class ResearchGap(BaseModel):
    """Identified research blindspot, missing source, or contradiction."""

    gap_id: str = Field(default_factory=lambda: f"gap_{uuid4().hex[:6]}")
    description: str
    severity: str = Field(default="medium", description="critical, high, medium, low")
    recommended_action: str
    target_agent: str = "document_researcher"


class CriticOutput(BaseModel):
    """Quality review, contradiction analysis, and gap assessment."""

    coverage_score: float = Field(..., ge=0.0, le=1.0)
    is_sufficient: bool
    contradictions_found: list[str] = Field(default_factory=list)
    gaps: list[ResearchGap] = Field(default_factory=list)
    recommendation: str = "proceed"  # proceed | revise | abort


# ============================================================================
# 5. Synthesizer Output Schemas
# ============================================================================


class ReportSection(BaseModel):
    """Structured report chapter/section with inline citation bindings."""

    title: str
    content: str
    cited_evidence_ids: list[str] = Field(default_factory=list)


class SynthesizerOutput(BaseModel):
    """Final grounded synthesis report produced strictly from verified evidence."""

    title: str
    executive_summary: str
    sections: list[ReportSection] = Field(..., min_length=1)
    limitations: list[str] = Field(default_factory=list)
    full_markdown: str
    total_citations: int = 0
